export const hasVisualDetailedSummaryContent = (inputs: SummaryInput[]): boolean => {
  return inputs.some(input =>
    input.blocks?.some(block => block.type === 'image') ||
    input.videoFrames?.some(frameSet => frameSet.images.length > 0)
  )
}

export const getDetailedSummarySystemPrompt = (
  inputs: SummaryInput[],
  options?: {
    markdownOutput?: boolean
  }
): string => {
  const hasVisual = hasVisualDetailedSummaryContent(inputs)

  if (options?.markdownOutput) {
    return hasVisual
      ? MULTIMODAL_DETAILED_SUMMARY_MARKDOWN_SYSTEM_PROMPT
      : TEXT_ONLY_DETAILED_SUMMARY_MARKDOWN_SYSTEM_PROMPT
  }

  return hasVisual
    ? MULTIMODAL_DETAILED_SUMMARY_SYSTEM_PROMPT
    : TEXT_ONLY_DETAILED_SUMMARY_SYSTEM_PROMPT
}
